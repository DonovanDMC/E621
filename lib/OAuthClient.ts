import { createE621Client, type Options } from "./client.js";
import { OAuthCallbackError } from "./errors.js";
import DoorkeeperOpenidConnectDiscovery from "./modules/DoorkeeperOpenidConnectDiscovery.js";
import DoorkeeperOpenidConnectUserinfo from "./modules/DoorkeeperOpenidConnectUserinfo.js";
import DoorkeeperTokenInfo from "./modules/DoorkeeperTokenInfo.js";
import DoorkeeperTokens from "./modules/DoorkeeperTokens.js";

import type {
    OAuthIntrospection,
    OAuthScope,
    OAuthToken,
    OAuthTokenInfo,
    OAuthUserInfo,
    OpenIDConfiguration,
} from "e621-openapi/types";

/** @category OAuth */
export interface OAuthClientOptions extends Pick<Options, "baseURL" | "ratelimit" | "requestTimeout" | "userAgent" | "userAgentInQuery"> {
    /** The client id (uid) of your OAuth application. */
    clientId: string;
    /**
     * The client secret of your OAuth application. Leave out for public clients (e.g. browser or
     * desktop apps, where the secret can't be kept private) - PKCE is always used either way.
     * @default none
     */
    clientSecret?: string;
    /**
     * Called whenever the stored token changes (exchanged, refreshed, or revoked - `null` in that case).
     * Use this to persist the token, and pass it back in as {@link OAuthClientOptions.token} later.
     * @default none
     */
    onToken?: (token: OAuthToken | null) => void | Promise<void>;
    /**
     * The redirect uri registered for your application. Used by default by
     * {@link OAuthClient.createAuthorizationURL} and {@link OAuthClient.exchangeCode}.
     * @default none
     */
    redirectURI?: string;
    /**
     * How many seconds before the access token expires that {@link OAuthClient.getAccessToken} should
     * refresh it.
     * @default 60
     */
    refreshLeeway?: number;
    /**
     * The scopes to request by default in {@link OAuthClient.createAuthorizationURL}.
     * @default none (the application's default scopes)
     */
    scopes?: Array<OAuthScope>;
    /**
     * A previously obtained token to restore, e.g. one saved from {@link OAuthClientOptions.onToken}.
     * @default none
     */
    token?: OAuthToken | null;
}

/** @category OAuth */
export interface AuthorizationURLOptions {
    /** Override the code verifier, a random one is generated by default. */
    codeVerifier?: string;
    /** Sent as the OpenID Connect `nonce`, included in the returned ID token. */
    nonce?: string;
    prompt?: "none" | "login" | "consent" | "select_account";
    /** @default {@link OAuthClientOptions.redirectURI} */
    redirectURI?: string;
    /** @default {@link OAuthClientOptions.scopes} */
    scopes?: Array<OAuthScope>;
    /** Override the state, a random one is generated by default. */
    state?: string;
}

/** @category OAuth */
export interface AuthorizationRequest {
    /** Must be kept (e.g. in the session) and passed to {@link OAuthClient.exchangeCode} or {@link OAuthClient.handleCallback}. */
    codeVerifier: string;
    redirectURI: string | null;
    /** Must be kept and checked against the callback's state - {@link OAuthClient.handleCallback} does this for you. */
    state: string;
    /** The url to send the user to. */
    url: string;
}

/** @category OAuth */
export interface HandleCallbackOptions {
    codeVerifier: string;
    /** @default {@link OAuthClientOptions.redirectURI} */
    redirectURI?: string;
    /** The state from {@link AuthorizationRequest.state}, compared against the one in the callback. */
    state: string;
}

function base64URL(bytes: Uint8Array): string {
    let str = "";
    for (const byte of bytes) str += String.fromCharCode(byte);
    return btoa(str).replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");
}

function randomString(byteLength = 32): string {
    return base64URL(crypto.getRandomValues(new Uint8Array(byteLength)));
}

/**
 * A helper for e621's OAuth 2.0 / OpenID Connect flow (authorization code + PKCE). It builds authorization
 * urls, exchanges codes, and keeps the token refreshed. Pass {@link OAuthClient.getAccessToken} as
 * {@link Options.authToken} to make requests as the authorized user:
 * ```ts
 * const oauth = new OAuthClient({ clientId: "...", redirectURI: "https://example.com/callback", scopes: ["openid", "full"] });
 * const { url, state, codeVerifier } = await oauth.createAuthorizationURL();
 * // send the user to `url`, then once they're redirected back:
 * await oauth.handleCallback(callbackURL, { state, codeVerifier });
 * const e621 = new E621({ authToken: oauth.getAccessToken });
 * ```
 *
 * OAuth 2.0 / OpenID Connect support is present in the spec but has not been publicly released on e621
 * yet - these endpoints are not yet available for use.
 *
 * @category OAuth
 */
export default class OAuthClient {
    private _clientSecret!: string | null;
    private _discovery!: DoorkeeperOpenidConnectDiscovery;
    private _onToken!: OAuthClientOptions["onToken"];
    private _refreshing!: Promise<OAuthToken> | null;
    private _token!: OAuthToken | null;
    private _tokenInfo!: DoorkeeperTokenInfo;
    private _tokens!: DoorkeeperTokens;
    private _userinfo!: DoorkeeperOpenidConnectUserinfo;
    readonly baseURL: string;
    readonly clientId: string;
    readonly redirectURI: string | null;
    readonly refreshLeeway: number;
    readonly scopes: Array<OAuthScope>;
    constructor(options: OAuthClientOptions) {
        const { clientId, clientSecret, onToken, redirectURI, refreshLeeway, scopes, token, ...clientOptions } = options;
        this.clientId = clientId;
        this.redirectURI = redirectURI ?? null;
        this.refreshLeeway = refreshLeeway ?? 60;
        this.scopes = scopes ?? [];
        // the token endpoints authenticate the application, never the user, so they get a client without user auth
        const { client, options: resolved } = createE621Client(clientOptions);
        const { client: authedClient } = createE621Client({ ...clientOptions, authToken: () => this.getAccessToken() });
        this.baseURL = resolved.baseURL;
        Object.defineProperties(this, {
            _clientSecret: { value: clientSecret ?? null, enumerable: false },
            _discovery: { value: new DoorkeeperOpenidConnectDiscovery(undefined, client), enumerable: false },
            _onToken: { value: onToken, enumerable: false },
            _refreshing: { value: null, writable: true, enumerable: false },
            _token: { value: token ?? null, writable: true, enumerable: false },
            _tokenInfo: { value: new DoorkeeperTokenInfo(undefined, authedClient), enumerable: false },
            _tokens: { value: new DoorkeeperTokens(undefined, client), enumerable: false },
            _userinfo: { value: new DoorkeeperOpenidConnectUserinfo(undefined, authedClient), enumerable: false },
        });
        this.getAccessToken = this.getAccessToken.bind(this);
    }

    /** Creates a PKCE `code_challenge` (S256) from a code verifier. */
    static async createCodeChallenge(codeVerifier: string): Promise<string> {
        const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(codeVerifier));
        return base64URL(new Uint8Array(digest));
    }

    /** Creates a random PKCE code verifier. */
    static createCodeVerifier(): string {
        return randomString(32);
    }

    /** Creates a random state value. */
    static createState(): string {
        return randomString(16);
    }

    /** When the current access token expires, as a unix timestamp in milliseconds - `null` if there's no token. */
    get expiresAt(): number | null {
        if (this._token === null) return null;
        return (this._token.created_at + this._token.expires_in) * 1000;
    }

    /** Whether the current access token is expired (or within {@link OAuthClientOptions.refreshLeeway} of expiring). */
    get isExpired(): boolean {
        const expiresAt = this.expiresAt;
        return expiresAt === null || Date.now() >= expiresAt - this.refreshLeeway * 1000;
    }

    /** The current token, if any. */
    get token(): OAuthToken | null {
        return this._token;
    }

    private _clientAuth(): { client_id: string; client_secret?: string } {
        return this._clientSecret === null ? { client_id: this.clientId } : { client_id: this.clientId, client_secret: this._clientSecret };
    }

    private _requireToken(): OAuthToken {
        if (this._token === null) throw new Error("No OAuth token is available, the user must authorize first.");
        return this._token;
    }

    /** Builds the url to send the user to, to authorize your application. */
    async createAuthorizationURL(options: AuthorizationURLOptions = {}): Promise<AuthorizationRequest> {
        const codeVerifier = options.codeVerifier ?? OAuthClient.createCodeVerifier();
        const state = options.state ?? OAuthClient.createState();
        const redirectURI = options.redirectURI ?? this.redirectURI;
        const scopes = options.scopes ?? this.scopes;
        const url = new URL("/oauth/authorize", this.baseURL);
        url.searchParams.set("response_type", "code");
        url.searchParams.set("client_id", this.clientId);
        if (redirectURI) url.searchParams.set("redirect_uri", redirectURI);
        if (scopes.length !== 0) url.searchParams.set("scope", scopes.join(" "));
        url.searchParams.set("state", state);
        url.searchParams.set("code_challenge", await OAuthClient.createCodeChallenge(codeVerifier));
        url.searchParams.set("code_challenge_method", "S256");
        if (options.nonce) url.searchParams.set("nonce", options.nonce);
        if (options.prompt) url.searchParams.set("prompt", options.prompt);

        return { codeVerifier, redirectURI, state, url: url.toString() };
    }

    /** Gets e621's OpenID Connect discovery document. */
    async discovery(): Promise<OpenIDConfiguration> {
        return this._discovery.provider();
    }

    /** Exchanges an authorization code for a token, and stores it. */
    async exchangeCode(code: string, codeVerifier: string, redirectURI: string | null = this.redirectURI): Promise<OAuthToken> {
        const token = await this._tokens.create({
            grant_type: "authorization_code",
            code,
            code_verifier: codeVerifier,
            redirect_uri: redirectURI ?? undefined,
            ...this._clientAuth(),
        });
        await this.setToken(token);
        return token;
    }

    /**
     * Gets a valid access token, refreshing it first if it's expired. Already bound, so it can be passed
     * directly as {@link Options.authToken}.
     */
    async getAccessToken(): Promise<string> {
        if (this._token === null) throw new Error("No OAuth token is available, the user must authorize first.");
        if (this.isExpired) return (await this.refresh()).access_token;
        return this._token.access_token;
    }

    /**
     * Validates the url the user was redirected back to (state, and any error e621 sent), then exchanges
     * its code for a token.
     * @param callbackURL - The full callback url, or just its query string.
     */
    async handleCallback(callbackURL: string | URL | URLSearchParams, options: HandleCallbackOptions): Promise<OAuthToken> {
        const params = callbackURL instanceof URLSearchParams
            ? callbackURL
            : typeof callbackURL === "string" && !/^[a-z][\d+.a-z-]*:/i.test(callbackURL)
                ? new URLSearchParams(callbackURL)
                : new URL(callbackURL).searchParams;
        const state = params.get("state");
        const error = params.get("error");
        if (error) throw new OAuthCallbackError(error, params.get("error_description"), state);
        if (state !== options.state) throw new OAuthCallbackError("invalid_state", "The callback's state does not match the expected state.", state);
        const code = params.get("code");
        if (!code) throw new OAuthCallbackError("invalid_request", "The callback is missing the authorization code.", state);
        return this.exchangeCode(code, options.codeVerifier, options.redirectURI ?? this.redirectURI);
    }

    /** Introspects a token - by default the current access token. */
    async introspect(token = this._requireToken().access_token): Promise<OAuthIntrospection> {
        return this._tokens.introspect({ token, ...this._clientAuth() });
    }

    /**
     * Refreshes the access token, and stores the new token. Concurrent calls share the same request.
     * @param scopes - Narrow the new token to these scopes.
     */
    async refresh(scopes?: Array<OAuthScope>): Promise<OAuthToken> {
        if (this._refreshing) return this._refreshing;
        const refreshToken = this._requireToken().refresh_token;
        this._refreshing = this._tokens.create({
            grant_type: "refresh_token",
            refresh_token: refreshToken,
            scope: scopes?.join(" "),
            ...this._clientAuth(),
        })
            .then(async (token) => {
                await this.setToken(token);
                return token;
            })
            .finally(() => {
                this._refreshing = null;
            });
        return this._refreshing;
    }

    /** Revokes the current token (which also invalidates its refresh token), and clears it. */
    async revoke(): Promise<void> {
        const token = this._requireToken();
        await this._tokens.revoke({ token: token.access_token, token_type_hint: "access_token", ...this._clientAuth() });
        await this.setToken(null);
    }

    /** Replaces the stored token, calling {@link OAuthClientOptions.onToken}. */
    async setToken(token: OAuthToken | null): Promise<void> {
        this._token = token;
        await this._onToken?.(token);
    }

    /** Gets metadata about the current access token. */
    async tokenInfo(): Promise<OAuthTokenInfo> {
        return this._tokenInfo.get();
    }

    /** Gets the OpenID Connect claims of the authorized user, gated by the token's scopes. */
    async userInfo(): Promise<OAuthUserInfo> {
        return this._userinfo.get();
    }
}
